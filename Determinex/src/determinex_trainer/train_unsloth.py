# Attempt B: Ollama create FROM merged dir (Ollama 0.5+ supports safetensors)
# Fallback:  Print manual-conversion instructions

_llama_env = os.environ.get("LLAMA_CPP_DIR")
LLAMA_CPP_CANDIDATES = [
    *([] if not _llama_env else [Path(_llama_env)]),
    Path("C:/llama.cpp"),
    Path.home() / "llama.cpp",
    Path.home() / "dev" / "llama.cpp",
]

gguf_produced = False
model_tag = f"determinex-engineer:v{args.version}"

if merged_dir and merged_dir.exists():
    # --- Attempt A: llama.cpp ---
    llama_root = next((p for p in LLAMA_CPP_CANDIDATES if p.exists()), None)
    convert_script = (llama_root / "convert_hf_to_gguf.py") if llama_root else None

    if convert_script and convert_script.exists():
        f16_gguf = output_dir / "model-f16.gguf"
        q4_gguf = output_dir / "model.gguf"
        print("\n[FORGE] Running llama.cpp convert_hf_to_gguf.py...", flush=True)

        r = subprocess.run(
            [
                sys.executable,
                str(convert_script),
                str(merged_dir),
                "--outfile",
                str(f16_gguf),
                "--outtype",
                "f16",
            ],
        )
        if r.returncode == 0:
            quantize_candidates = [
                llama_root / "quantize",
                llama_root / "quantize.exe",
                llama_root / "build" / "bin" / "quantize",
                llama_root / "build" / "bin" / "Release" / "llama-quantize.exe",
                llama_root / "build" / "bin" / "llama-quantize",
            ]
            quantize_bin = next((p for p in quantize_candidates if p.exists()), None)
            if quantize_bin:
                r2 = subprocess.run([str(quantize_bin), str(f16_gguf), str(q4_gguf), "Q4_K_M"])
                if r2.returncode == 0:
                    f16_gguf.unlink(missing_ok=True)
                    print(f"[FORGE] GGUF (Q4_K_M): {q4_gguf}", flush=True)
                    gguf_produced = True
                else:
                    # Keep F16 GGUF — still usable, just larger (~14 GB)
                    q4_gguf.rename(q4_gguf.with_suffix(".q4_failed"))
                    print(f"[FORGE] GGUF (F16, quantize failed): {f16_gguf}", flush=True)
                    gguf_produced = True
            else:
                print(f"[FORGE] GGUF (F16, no quantize binary): {f16_gguf}", flush=True)
                gguf_produced = True
        else:
            print("[FORGE] convert_hf_to_gguf.py failed — see output above.", flush=True)

    # --- Attempt B: Ollama create FROM merged dir ---
    if not gguf_produced:
        modelfile_path = _DETERMINEX_ROOT / f"Modelfile.engineer.v{args.version}"
        modelfile_path.write_text(
            f"FROM {merged_dir.as_posix()}\n"
            f"PARAMETER num_ctx {MAX_SEQ_LENGTH}\n"
            f"PARAMETER temperature 0\n",
            encoding="utf-8",
        )
        print("\n[FORGE] Attempting Ollama import from HF directory...", flush=True)
        r = subprocess.run(
            ["ollama", "create", model_tag, "-f", str(modelfile_path)],
            capture_output=True,
            text=True,
        )
        if r.returncode == 0:
            print(f"[FORGE] Ollama imported successfully: {model_tag}", flush=True)
            # Write a marker so ignite_loop.py promote_model() skips the GGUF search
            marker = output_dir / "ollama_promoted.txt"
            marker.write_text(model_tag, encoding="utf-8")
            gguf_produced = True  # model is live in Ollama, treat as promoted
        else:
            print(f"[FORGE] Ollama direct import failed:\n  {r.stderr[:300]}", flush=True)

