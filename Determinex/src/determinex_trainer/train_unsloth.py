"""
train_unsloth.py — Determinex Engineer Fine-Tuning (Standard PEFT)

Replaces Unsloth with standard HuggingFace PEFT — eliminates Windows
dependency hell. Base model: microsoft/Phi-3-mini-4k-instruct (3.8B).

Hardware budget (6 GB VRAM — Tier 0 GPU):
  - Phi-3-mini 4-bit NF4     : ~2.3 GB
  - LoRA r=16 overhead       : ~0.2 GB
  - Gradient checkpointing   : saves ~40% vs no-checkpoint
  - Training peak (batch=1)  : ~3.5–4.0 GB — comfortable headroom on 6 GB

GGUF Export Strategy (in order of attempt):
  1. llama.cpp convert_hf_to_gguf.py + quantize  (if llama.cpp found)
  2. Ollama create from merged HF directory       (Ollama 0.5+ safetensors)
  3. Emit manual-conversion instructions and exit cleanly

Usage:
  python train_unsloth.py [--version N] [--output_dir DIR] [--epochs N]
  python train_unsloth.py --version 4 --per_device_batch_size 1 --max_seq_length 2048
"""

