# ---------------------------------------------------------------------------
# 8. MERGE LoRA INTO BASE MODEL
# ---------------------------------------------------------------------------
# We move the trained PEFT model to CPU BEFORE deleting it, then merge_and_unload.
# This avoids having to reload the base model in FP16 (which would fail for
# pre-quantized bnb-4bit models like unsloth/Llama-3.2-3B-Instruct-bnb-4bit).
# Memory: 3B model on CPU ≈ 6 GB system RAM — well within 19 GB pool.

print("\n[FORGE] Moving trained model to CPU for merge (~1 min)...", flush=True)
merged_dir = None

try:
    # ── Step A: free GPU memory ───────────────────────────────────────────────
    # The 4-bit bnb training model CANNOT be cast to fp16 in-place (bitsandbytes
    # restriction). Delete it to free VRAM, then load a clean fp16 base on CPU.
    del trainer
    del model
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    # ── Step B: load FP16 base on CPU for clean merge ─────────────────────────
    # unsloth/Llama-3.2-3B-Instruct is the non-quantized variant (~6 GB RAM,
    # no VRAM needed — merge happens entirely on CPU).
    MERGE_BASE = "unsloth/Llama-3.2-3B-Instruct"
    print(f"\n[FORGE] Loading FP16 base for merge: {MERGE_BASE}", flush=True)
    print("[FORGE] (CPU-only, ~3–5 min — GPU is free during this step)", flush=True)

    from peft import PeftModel as _PeftModel

    merge_base = AutoModelForCausalLM.from_pretrained(
        MERGE_BASE,
        torch_dtype=torch.float16,
        device_map="cpu",
    )
    print("[FORGE] FP16 base loaded. Applying LoRA adapter...", flush=True)

    peft_for_merge = _PeftModel.from_pretrained(merge_base, str(lora_dir))
    print("[FORGE] Merging LoRA weights into base model...", flush=True)

    merged_model = peft_for_merge.merge_and_unload()
    del merge_base
    del peft_for_merge
    gc.collect()

    merged_dir = output_dir / "merged"
    merged_dir.mkdir(exist_ok=True)
    merged_model.save_pretrained(str(merged_dir), safe_serialization=True)
    tokenizer.save_pretrained(str(merged_dir))
    print(f"[FORGE] Merged FP16 model saved: {merged_dir}", flush=True)

    del merged_model
    gc.collect()

except Exception as e:
    print(f"[FORGE] WARNING: Merge step failed: {e}", flush=True)
    print("[FORGE] LoRA adapter is still saved — merge manually later.", flush=True)

# ---------------------------------------------------------------------------
# 9. GGUF EXPORT
# ---------------------------------------------------------------------------
