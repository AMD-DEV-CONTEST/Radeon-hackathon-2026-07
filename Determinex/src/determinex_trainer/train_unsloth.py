# ---------------------------------------------------------------------------
# 4. FORMAT PROMPTS — Llama-3.2 instruction format
# ---------------------------------------------------------------------------
# Llama-3.2-Instruct uses special role header tokens.
# This matches what Ollama uses for `llama3.2:3b` inference.


def format_prompts(examples):
    texts = []
    for sys_p, user_p, asst_p in zip(examples["system"], examples["user"], examples["assistant"]):
        text = (
            f"<|begin_of_text|>"
            f"<|start_header_id|>system<|end_header_id|>\n\n{sys_p}<|eot_id|>"
            f"<|start_header_id|>user<|end_header_id|>\n\n{user_p}<|eot_id|>"
            f"<|start_header_id|>assistant<|end_header_id|>\n\n{asst_p}<|eot_id|>"
        )
        texts.append(text)
    return {"text": texts}


print("[FORGE] Applying Llama-3.2 instruction format...", flush=True)
dataset = raw_dataset.map(format_prompts, batched=True)
print("[FORGE] Format applied.", flush=True)

# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
# 4b. GPU THROTTLE CALLBACK
# ---------------------------------------------------------------------------
# Sleeps for --throttle seconds after every gradient step.
# On Windows with a single display GPU, sustained 98% utilisation
# starves the Windows compositor of GPU time and causes the display to hang.
# A short sleep per step gives the OS regular windows to push frames.
# Default 0.15s adds ~45s to a 300-step run — an acceptable tradeoff.


class GpuThrottleCallback(TrainerCallback):
    def __init__(self, sleep_secs: float):
        self.sleep_secs = sleep_secs

    def on_step_end(
        self,
        _args,
        _state: TrainerState,
        control: TrainerControl,
        **kwargs,
    ) -> TrainerControl:
        if self.sleep_secs > 0:
            time.sleep(self.sleep_secs)
        return control


_throttle_callbacks = [GpuThrottleCallback(args.throttle)] if args.throttle > 0 else []

if args.throttle > 0:
    print(
        f"[FORGE] GPU throttle: {args.throttle * 1000:.0f}ms sleep per gradient step "
        f"(disable with --throttle 0)",
        flush=True,
    )

