#!/usr/bin/env python3
"""
ProgramBench Repair Context Injector (Layer 3).

Generates a markdown repair context block to prepend to ForgeDaemon repair prompts.
References behavioral proofs from locked tools that share traits with the target.

Usage:
  python scripts/pb_repair_context.py --tool trdsql --failing-categories "test_sql_query,test_output_format,test_flags"
  python scripts/pb_repair_context.py --tool grex --top 2
"""

import argparse
import json
import subprocess
import sys
import tarfile
from pathlib import Path

SIG_DIR = Path("corpus/programbench/behavior_signatures")
LOCKED_DIR = Path("corpus/programbench/locked")
BOARD_PATH = Path("logs/programbench_lock_board.json")


def get_top_similar(tool: str, failing_cats: list[str], top: int = 3) -> list[dict]:
    """Call pb_corpus_router.py and return top matches."""
    cmd = [
        sys.executable,
        "scripts/pb_corpus_router.py",
        "--tool",
        tool,
        "--top",
        str(top),
        "--json",
    ]
    if failing_cats:
        cmd += ["--failing-categories", ",".join(failing_cats)]
    try:
        result = subprocess.run(cmd, capture_output=True, text=True, check=True)
        data = json.loads(result.stdout)
        return data.get("matches", [])
    except Exception as e:
        print(f"Router error: {e}", file=sys.stderr)
        return []


def extract_executable_block(tarball_path: Path) -> str:
    """Extract the executable block from compile.sh inside a submission tarball."""
    if not tarball_path.exists():
        return ""
    try:
        with tarfile.open(tarball_path, "r:gz") as tf:
            names = tf.getnames()
            sh_name = next((n for n in names if n.endswith("compile.sh")), None)
            if not sh_name:
                return ""
            content = tf.extractfile(sh_name).read().decode("utf-8", errors="replace")
        import re

        m = re.search(r"(cat\s*>\s*\S*executable\s*<<'EXEC_EOF'.*?EXEC_EOF)", content, re.DOTALL)
        return m.group(1) if m else ""
    except Exception:
        return ""


def get_tool_board_entry(slug: str) -> dict:
    board = json.loads(BOARD_PATH.read_text(encoding="utf-8"))
    return next(
        (e for e in board if slug in e.get("base_slug", "") or e.get("base_slug", "") in slug),
        {},
    )


def describe_tags(tags: list[str]) -> str:
    if not tags:
        return "general-purpose CLI tool"
    return ", ".join(tags[:4])


def generate_repair_context(
    target_tool: str,
    failing_categories: list[str],
    top_matches: list[dict],
) -> str:
    entry = get_tool_board_entry(target_tool)
    official_score = entry.get("official_score_pct", 0.0)
    not_run = entry.get("official_not_run", 0)
    passed = entry.get("official_passed", 0)
    total = entry.get("official_total", 0)

    # Count failing category occurrences from the eval report
    tool_name = target_tool.split("__")[-1] if "__" in target_tool else target_tool
    failing_summary = ""
    if failing_categories:
        failing_summary = "\n".join(f"  - `{c}`" for c in failing_categories[:5])
    else:
        failing_summary = "  (no specific categories provided — run eval to extract)"

    lines = [
        "<!-- DETERMINEX REPAIR CONTEXT — auto-generated by pb_repair_context.py -->",
        "",
        "## Repair Context: Behavioral Reference Corpus",
        "",
        f"### Target Tool: `{tool_name}`",
        f"- Official score: **{official_score:.1f}%** ({passed}/{total} tests, {not_run} not_run)",
        "- Top failing test categories:",
        failing_summary,
        "",
        "---",
        "",
        "### Reference Implementations (100% official score, zero not_run)",
        "",
        "The following locked tools passed their FULL official test suites under identical",
        "Docker conditions. Use their wrapper patterns and behavioral structure as ground truth.",
        "",
    ]

    for i, match in enumerate(top_matches, 1):
        slug = match["slug"]
        score = match["score"]
        lang = match["language"]
        build = match["build_system"]
        tags = match["behavioral_tags"]
        categories = match["test_categories"]
        wrapper_pat = match["wrapper_pattern"]

        tool_short = slug.split("__")[-1] if "__" in slug else slug
        tarball = LOCKED_DIR / tool_short / "submission.tar.gz"
        exec_block = extract_executable_block(tarball)

        lines += [
            f"#### Reference {i}: `{tool_short}` (similarity: {score}pt)",
            f"- Language: `{lang}` | Build: `{build}` | Wrapper: `{wrapper_pat}`",
            f"- Behavioral profile: {describe_tags(tags)}",
            f"- Test categories: {', '.join(f'`{c}`' for c in categories[:5])}",
            "",
        ]

        if exec_block:
            lines += [
                "**Executable wrapper (proven working):**",
                "```sh",
                exec_block.strip(),
                "```",
                "",
            ]
        else:
            lines.append(f"_(executable block unavailable — see {tarball})_\n")

    lines += [
        "---",
        "",
        "### Repair Directive",
        "",
        "The reference implementations above passed **100% of their official test suites**.",
        "When repairing the target tool:",
        "",
        "1. Match the wrapper pattern of the closest reference (same language + behavioral tags)",
        "2. If the target has `not_run` tests: verify no `del items[N:]` cap in compile.sh conftest",
        "3. If tests are TUI-filtered: confirm the test actually imports pexpect/libtmux before filtering",
        "4. Binary name must match exactly what tests expect — check test file for `EXECUTABLE = ...`",
        "5. Run `python scripts/pb_override_scan.py --guard` before archiving any lock",
        "",
        "<!-- END DETERMINEX REPAIR CONTEXT -->",
    ]

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate repair context for ForgeDaemon prompts")
    parser.add_argument("--tool", required=True, help="Target tool slug or short name")
    parser.add_argument(
        "--failing-categories",
        type=str,
        default="",
        help="Comma-separated failing test category names",
    )
    parser.add_argument("--top", type=int, default=3, help="Number of reference tools to include")
    parser.add_argument("--output", type=str, help="Write output to file instead of stdout")
    args = parser.parse_args()

    failing_cats = [c.strip() for c in args.failing_categories.split(",") if c.strip()]
    top_matches = get_top_similar(args.tool, failing_cats, args.top)

    if not top_matches:
        print(
            f"No similar locked tools found for '{args.tool}'. "
            "Run: python scripts/pb_corpus_behavior.py --all",
            file=sys.stderr,
        )
        sys.exit(1)

    context = generate_repair_context(args.tool, failing_cats, top_matches)

    if args.output:
        Path(args.output).write_text(context, encoding="utf-8")
        print(f"Context written to {args.output}")
    else:
        print(context)


if __name__ == "__main__":
    main()
