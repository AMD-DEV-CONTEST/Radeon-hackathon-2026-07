FOOTER = (
    '<div style="font-size:7pt;color:#94a3b8;width:100%;padding:0 15mm;'
    'font-family:Segoe UI,sans-serif;display:flex;justify-content:space-between;">'
    "<span>Determinex &middot; Track 2 Project Specification &middot; AGPL-3.0-or-later</span>"
    '<span class="pageNumber"></span>/<span class="totalPages"></span></div>'
)


#: The architecture DAG, drawn in CSS. mermaid is not vendored in frontend/node_modules and
#: the renderer runs offline, so a ```mermaid fence shipped as raw diagram SOURCE in the PDF --
#: which is worse than no diagram, because it looks like a mistake rather than a decision.
_FLOW = [
    ("idea / spec", "", "plain"),
    ("C7 ARCHITECT", "7B Mistral &middot; decomposes into an ordered DAG", "box"),
    ("C1 BUILDER &mdash; the only GPU node",
     "1.5B Qwen2.5-Coder &middot; K candidates, varied temperature", "gpu"),
    ("ORACLE &mdash; deterministic, not a model",
     "rustc &middot; go build &middot; pytest &middot; tsc &middot; dotnet &middot; gcc<br>"
     "<i>the only node in the loop that decides anything</i>", "oracle"),
    ("commit to WAL, advance to the next step", "", "plain"),
    ("C3 MONITOR", "3B Llama-3.2 &middot; scores, may submit a rival approach", "box"),
    ("ADJUDICATOR",
     "ROUTE &rarr; MATCH &rarr; UNBLOCK &rarr; IMPOSSIBLE<br>"
     "IMPOSSIBLE requires a proof; else NEEDS_WORK", "box"),
]


def _render_flow(html: str) -> str:
    """Replace the mermaid source block with a CSS-drawn version of the same graph."""
    m = re.search(r"<pre><code[^>]*>\s*flowchart TD.*?</code></pre>", html, re.S)
    if not m:
        return html
    parts = ['<div class="flow">']
    for i, (head, sub, kind) in enumerate(_FLOW):
        if i:
            parts.append('<div class="arrow">&darr;</div>')
        parts.append(
            f'<div class="node {kind}"><div class="nh">{head}</div>'
            + (f'<div class="ns">{sub}</div>' if sub else "")
            + "</div>"
        )
    parts.append(
        '<div class="feedback">FAIL &mdash; the exact compiler error is injected '
        "<i>verbatim</i> into the next Builder prompt</div></div>"
    )
    return html[: m.start()] + "".join(parts) + html[m.end():]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--md", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--logo", default=str(_ROOT / "frontend/src-tauri/icons/128x128@2x.png"))
    a = ap.parse_args()

    import markdown

    src = Path(a.md).read_text(encoding="utf-8")

    # The first four lines are the cover block in the markdown; lift them into the dark
    # header rather than letting them render as ordinary body text.
    lines = src.splitlines()
    title = lines[0].lstrip("# ").strip()
    def _inline(t: str) -> str:
        """Inline markdown -> HTML. The cover lines are markdown too, and stripping `*`
        only from the ends left `Submitter:** DarthCeltic · **Source:**` on the cover."""
        t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
        t = re.sub(r"\[(.+?)\]\((.+?)\)", r'<a href="\2">\1</a>', t)
        t = re.sub(r"(?<![\w/])((?:github\.com|huggingface\.co)/[\w.\-/]+)",
                   r'<a href="https://\1">\1</a>', t)
        return t

    tag, meta = "", []
    for ln in lines[1:8]:
        s = ln.strip()
        if not s or s.startswith("---"):
            continue
        if not tag:
            tag = _inline(s.strip("*"))
        else:
            meta.append(_inline(s))
    body_md = "\n".join(lines[8:]) if len(lines) > 8 else src

    html_body = markdown.markdown(
        body_md,
        extensions=["tables", "fenced_code", "sane_lists", "attr_list"],
    )
    # GitHub-flavoured strikethrough is not in python-markdown's core.
    html_body = re.sub(r"~~(.+?)~~", r"<del>\1</del>", html_body)
    # mermaid is not vendored and the renderer is offline, so the fence would
    # otherwise ship as raw diagram SOURCE. Draw the same graph in CSS instead.
    html_body = _render_flow(html_body)

    logo = ""
    lp = Path(a.logo)
    if lp.exists():
        b64 = base64.b64encode(lp.read_bytes()).decode()
        logo = f'<img src="data:image/png;base64,{b64}" alt="">'

    meta_html = "<br>".join(meta)
    doc = (
        f"<!doctype html><html><head><meta charset='utf-8'><style>{CSS}</style></head><body>"
        f"<div class='cover'>{logo}<h1>{title}</h1>"
        f"<div class='tag'>{tag}</div><div class='meta'>{meta_html}</div></div>"
        f"{html_body}</body></html>"
    )

    with tempfile.TemporaryDirectory() as td:
        page = Path(td) / "spec.html"
        page.write_text(doc, encoding="utf-8")
        # The script must live inside frontend/ -- node resolves bare ESM specifiers like
        # 'playwright' relative to the SCRIPT's directory, not the cwd, so a temp-dir script
        # cannot see frontend/node_modules however it is invoked.
        script = _ROOT / "frontend" / "_spec_pdf_render.mjs"
        script.write_text(
            "import { chromium } from 'playwright';\n"
            "const [src, out, footer] = process.argv.slice(2);\n"
            "const b = await chromium.launch();\n"
            "const p = await b.newPage();\n"
            "await p.goto('file:///' + src.replace(/\\\\/g, '/'), "
            "{ waitUntil: 'networkidle' });\n"
            "await p.pdf({ path: out, format: 'A4', printBackground: true,\n"
            "  displayHeaderFooter: true, headerTemplate: '<div></div>',\n"
            "  footerTemplate: footer,\n"
            "  margin: { top: '18mm', bottom: '20mm', left: '0mm', right: '0mm' } });\n"
            "await b.close();\n",
            encoding="utf-8",
        )
        r = subprocess.run(
            ["node", str(script), str(page), str(Path(a.out).resolve()), FOOTER],
            cwd=str(_ROOT / "frontend"), capture_output=True, text=True, timeout=300,
        )
        if r.returncode != 0:
            sys.stderr.write(r.stderr[-2000:] + "\n")
            return 1

    size = Path(a.out).stat().st_size
    print(f"  wrote {a.out}  ({size / 1024:.0f} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
