#!/usr/bin/env python3
"""
spec_to_pdf.py — render PROJECT_SPEC.md to the submission PDF, deterministically.

The AMD Track 2 rules require project documentation as a PDF. It had been produced by hand,
which meant every correction to the spec needed a manual regeneration, and twice the PDF that
existed was several fixes behind the markdown it claimed to render -- including one that still
carried duplicate section numbers and a promise of a section that did not exist.

A document generated by a repeatable command cannot drift from its source. That is the same
argument this project makes about oracles, applied to its own paperwork.

    python scripts/dev/spec_to_pdf.py --md <spec.md> --out <out.pdf>

Renders through the Playwright Chromium already vendored in frontend/node_modules, so it needs
no new dependency and no network.
"""

