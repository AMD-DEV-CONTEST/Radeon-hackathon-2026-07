def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    html = _ROOT / "frontend" / "_deck.html"
    html.write_text(build(), encoding="utf-8")
    js = _ROOT / "frontend" / "_deck_render.mjs"
    js.write_text(
        "import { chromium } from 'playwright';\n"
        "const [src, out] = process.argv.slice(2);\n"
        "const b = await chromium.launch();\n"
        "const p = await b.newPage();\n"
        "await p.goto('file:///' + src.replace(/\\\\/g, '/'), { waitUntil: 'networkidle' });\n"
        "await p.pdf({ path: out, width: '254mm', height: '143mm', printBackground: true });\n"
        "await b.close();\n",
        encoding="utf-8",
    )
    r = subprocess.run(
        ["node", str(js), str(html), str(Path(a.out).resolve())],
        cwd=str(_ROOT / "frontend"), capture_output=True, text=True, timeout=300,
    )
    js.unlink(missing_ok=True)
    html.unlink(missing_ok=True)
    if r.returncode != 0:
        print(r.stderr[-1500:])
        return 1
    print(f"  wrote {a.out}  ({Path(a.out).stat().st_size / 1024:.0f} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
