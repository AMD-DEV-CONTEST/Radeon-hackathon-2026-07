TOOL_VERSION = "0.1.0"


def _usage() -> str:
    return f"usage: {{TOOL_NAME}} [OPTIONS] [ARGS]\\nTry '{{TOOL_NAME}} --help' for more information."


def _help() -> str:
    return (
        f"{{TOOL_NAME}} {{TOOL_VERSION}}\\n\\n"
        f"Usage: {{TOOL_NAME}} [OPTIONS] [ARGS]\\n\\n"
        f"Options:\\n"
        f"  -h, --help        Print help\\n"
        f"  -V, --version     Print version\\n"
        f"  -v, --verbose     Verbose output\\n"
        f"  -q, --quiet       Quiet output\\n"
        f"  --json            Emit JSON output\\n"
    )


