def load_pb_tasks() -> dict:
    """slug -> {lang, tool_name, tests}."""
    meta = {}
    with PB_TASKS.open(encoding="utf-8") as f:
        next(f)
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 6:
                continue
            _, instance_short, lang, _, tests, _ = parts[:6]
            slug = instance_short.lower().replace("/", "__")
            tool_name = instance_short.split("/", 1)[-1].lower()
            meta[slug] = {"lang": lang, "tool_name": tool_name, "tests": int(tests)}
    return meta


def load_slug_to_id() -> dict:
    return json.loads(SLUG_TO_ID.read_text(encoding="utf-8"))


def load_evaluated() -> dict:
    """tool_key -> dict with pct, dominant_bucket, failed_count."""
    fails = {}
    try:
        fails = json.loads(PER_TOOL_FAIL.read_text(encoding="utf-8"))
    except Exception:
        return {}
    return fails


def generate_one(tool_key: str, ours: dict, tool_meta: dict, dry_run: bool) -> bool:
    """Generate override for one tool."""
    instance_id = tool_key
    slug = tool_key.rsplit(".", 1)[0] if "." in tool_key else tool_key
    if slug not in tool_meta:
        return False
    meta = tool_meta[slug]
    pct = ours.get("pct", 0)
    buckets = ours.get("top_buckets") or []
    dominant = buckets[0][0] if buckets else "none"

    cluster_patch_block = ""
    for bucket, _count in buckets[:3]:  # top 3 clusters
        patch = cluster_patch(bucket, meta["tool_name"])
        if patch:
            cluster_patch_block += patch + "\n"

    body = OVERRIDE_TEMPLATE.format(
        instance_id=instance_id,
        tool_name=meta["tool_name"],
        language=meta["lang"],
        our_pct=pct,
        dominant_bucket=dominant,
        tool_name_repr=repr(meta["tool_name"]),
        cluster_patch_block=cluster_patch_block,
    )

    target_dir = OVERRIDES_DIR / instance_id
    target = target_dir / "main.py"

    if dry_run:
        return True
    target_dir.mkdir(parents=True, exist_ok=True)
    target.write_text(body, encoding="utf-8", newline="\n")
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--threshold",
        type=float,
        default=30.0,
        help="generate overrides for tools with pct < threshold",
    )
    ap.add_argument(
        "--skip-existing", action="store_true", help="don't overwrite existing overrides"
    )
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    tool_meta = load_pb_tasks()
    fails = load_evaluated()

    if not fails:
        print("ERROR: per_tool_failures.json missing — run per_tool_failures.py first.")
        return

    candidates = []
    for tool_key, data in fails.items():
        if data.get("pct", 0) >= args.threshold:
            continue
        if args.skip_existing and (OVERRIDES_DIR / tool_key / "main.py").exists():
            continue
        candidates.append((tool_key, data))

    candidates.sort(key=lambda kv: -kv[1].get("pct", 0))

    print(f"Tools below {args.threshold}%: {len(candidates)}")
    if args.dry_run:
        print(f"Would generate {len(candidates)} overrides.")
        for tk, d in candidates[:5]:
            print(f"  {tk}: pct={d.get('pct', 0)} dominant={d.get('top_buckets', [['?']])[0][0]}")
        return

    generated = 0
    for tk, d in candidates:
        ok = generate_one(tk, d, tool_meta, dry_run=False)
        if ok:
            generated += 1
    print(f"Generated {generated} override main.py files in {OVERRIDES_DIR}")


if __name__ == "__main__":
    main()
