def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def json_bytes(value: object) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode(
        "utf-8"
    )


def product_png() -> bytes:
    stream = io.BytesIO()
    image = Image.new("RGBA", (720, 960), (241, 238, 228, 255))
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((92, 100, 628, 860), radius=72, fill=(22, 31, 29, 255))
    draw.rounded_rectangle((150, 180, 570, 780), radius=42, fill=(231, 255, 245, 255))
    draw.rectangle((210, 278, 510, 550), fill=(40, 104, 86, 255))
    draw.ellipse((285, 610, 435, 760), fill=(246, 169, 72, 255))
    image.save(stream, format="PNG", optimize=True)
    return stream.getvalue()


