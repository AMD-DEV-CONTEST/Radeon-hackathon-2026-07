#!/bin/bash
set -e

echo "=== Testing Rust Code Generation ==="

MODELS=(
    "moving-company-10obj/attempt-01" 
    "moving-company-30obj/attempt-02" 
    "school-service-3obj/attempt-01"
)

for model_path in "${MODELS[@]}"; do
    echo "Testing $model_path..."
    ARTIFACT_DIR="${FLINT_RUNS_DIR:-../runs}/availability-eval-$model_path"
    
    if [ ! -d "$ARTIFACT_DIR" ]; then
        echo "Artifact dir $ARTIFACT_DIR not found, skipping."
        continue
    fi

    model_name=$(echo $model_path | cut -d'/' -f1)
    TEST_DIR="/tmp/rust-test-$model_name"
    rm -rf "$TEST_DIR"
    mkdir -p "$TEST_DIR"
    
    # Copy the XML model files
    cp -r "$ARTIFACT_DIR"/*.xml "$TEST_DIR"/
    
    cd "$TEST_DIR"
    
    # Generate the Rust code
    echo "  Generating rust-lib-core..."
    cargo teaql --input . rust-lib-core >/dev/null 2>&1
    
    # Fix the dependency conflict generated by cargo-teaql 2.0.8
    if [ -f "build/lib/Cargo.toml" ]; then
        echo "  Fixing Cargo.toml rusqlite dependency version..."
        sed -i 's/rusqlite = { version = "0.32"/rusqlite = { version = "0.40"/' build/lib/Cargo.toml
    fi
    
    # Run cargo check
    echo "  Running cargo check..."
    cd build/lib
    cargo check
    
    echo "✅ $model_name Rust Generation & Check Passed!"
    echo "----------------------------------------"
done

echo "All Rust generation tests completed successfully."
