"""
schemas.py - Pydantic data schemas for EduCopilot
All structured data models used across the application.
"""

from pydantic import BaseModel, Field
from typing import List, Optional


# ── Course & Planning ──────────────────────────────────────────────

class CourseOutcome(BaseModel):
    """Represents a single Course Outcome (CO) with Bloom's Taxonomy validation."""
    co_id: str = Field(..., description="Course Outcome identifier, e.g., CO1, CO2")
    statement: str = Field(..., description="Actionable outcome statement")
    blooms_level: str = Field(
        ...,
        description="Bloom's Taxonomy Level: Remember, Understand, Apply, Analyze, Evaluate, Create"
    )
    is_valid: bool = Field(
        ...,
        description="True if action verb matches Bloom's taxonomy guidelines"
    )
    feedback: Optional[str] = Field(
        None,
        description="Suggested improvements if invalid"
    )


class LessonPlanItem(BaseModel):
    """A single lecture entry in the lesson plan schedule."""
    lecture_num: int = Field(..., description="Sequential lecture number")
    module_name: str = Field(..., description="Module/Unit title")
    topic_description: str = Field(..., description="Detailed topic to cover")
    target_co: str = Field(..., description="Associated Course Outcome ID")
    pedagogy: str = Field(
        ...,
        description="Suggested teaching method: Lecture, Lab, Case Study, Group Discussion"
    )


class LessonPlan(BaseModel):
    """Complete lesson plan including outcomes and schedule."""
    course_code: str
    course_title: str
    outcomes: List[CourseOutcome]
    schedule: List[LessonPlanItem]


# ── Class Logging & Feedback ───────────────────────────────────────

class ClassLogEntry(BaseModel):
    """Enhanced log entry for tracking daily class progress with feedback."""
    lecture_num: int
    topics_covered: str
    completed_on_schedule: bool
    delay_reason: Optional[str] = None
    teacher_comments: Optional[str] = Field(
        None, description="Teacher's notes about what went well or badly"
    )
    student_questions: Optional[str] = Field(
        None, description="Notable questions raised by students during class"
    )
    pace_notes: Optional[str] = Field(
        None, description="Notes on pace: too fast, too slow, just right"
    )


# ── Student ────────────────────────────────────────────────────────

class StudentProfile(BaseModel):
    """Student performance profile with cohort classification."""
    student_id: str
    student_name: str
    average_score: float
    cohort: str = Field(..., description="Remedial, Average, or Advanced")
    weak_cos: List[str] = Field(default_factory=list)
    strength_cos: List[str] = Field(default_factory=list, description="COs where student excels")
    teacher_notes: Optional[str] = Field(None, description="Teacher's personal notes about student")


# ── Assessment & Exams ─────────────────────────────────────────────

class Question(BaseModel):
    """A single exam question with metadata."""
    question_id: int
    question_text: str
    target_co: str
    blooms_level: str
    marks: int
    sample_answer: str


class AdaptiveExamPaper(BaseModel):
    """An adaptive exam paper tailored to a specific cohort."""
    title: str
    cohort_target: str
    total_marks: int
    questions: List[Question]


class GeneratedContent(BaseModel):
    """Content generated by the content agent (slides, handouts, notes)."""
    content_type: str = Field(..., description="slides, handout, or teacher_notes")
    title: str
    lecture_num: Optional[int] = None
    markdown_content: str


# ── Evaluation ─────────────────────────────────────────────────────

class EvaluatedQuestion(BaseModel):
    """A single evaluated question from a scanned assignment."""
    question_num: int
    student_answer_summary: str
    marks_awarded: float
    marks_possible: float
    feedback: str
    co_id: str


class EvaluationResult(BaseModel):
    """Result of evaluating a scanned assignment/quiz."""
    student_id: Optional[str] = Field(None, description="Detected or inferred student ID")
    student_name: Optional[str] = Field(None, description="Detected or inferred student name")
    assessment_type: str = Field(..., description="quiz, assignment, midterm, etc.")
    total_marks_awarded: float
    total_marks_possible: float
    percentage: float
    questions: List[EvaluatedQuestion]
    overall_feedback: str
    recommended_cohort: str = Field(..., description="Remedial, Average, or Advanced based on this assessment")


# ── Accreditation ──────────────────────────────────────────────────

class NBAAttainmentReport(BaseModel):
    """NBA/ABET accreditation attainment report for a single CO."""
    co_id: str
    target_score_pct: float
    actual_score_pct: float
    attainment_status: str = Field(..., description="Attained or Not Attained")
    continuous_improvement_action: str


# ── Student Profiling ──────────────────────────────────────────────

class StudentInsight(BaseModel):
    """AI-generated insight about a student's performance."""
    student_id: str
    student_name: str
    overall_assessment: str
    strengths: List[str]
    areas_for_improvement: List[str]
    recommended_actions: List[str]


class ClassInsight(BaseModel):
    """AI-generated insight about overall class performance."""
    summary: str
    top_performers: List[str]
    at_risk_students: List[str]
    weak_topics: List[str]
    class_focus_areas: List[str]
    recommended_teacher_actions: List[str]
