    relation_changes: list = field(default_factory=list)
    timeline_events: list = field(default_factory=list)
    conflicts: list = field(default_factory=list)
    emotion_tone: str = ""
    plot_function: str = ""
    raw_response: str = ""
    model: str = ""
    prompt_profile_id: str = ""
    created_at: str = ""

