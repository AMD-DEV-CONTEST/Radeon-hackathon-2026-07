# ── ImportPipeline: orchestrator with hook points ──────────────────────────

class ImportPipeline:
    """Structured import pipeline with internal hook points.
    
    Pipeline: text → chapter_split → chapter_analysis → cross_chapter_merge
              → changeset_build → user_preview → user_confirm → commit
              → vector_store_update → global_index_sync
    
    Hook points (reserved for internal modules):
      before_chapter_split, after_chapter_split
      before_chapter_analysis, after_chapter_analysis
      before_cross_chapter, after_cross_chapter
      before_changeset_build, after_changeset_build
      before_commit, after_commit
      on_import_failed
    """

    def __init__(self, provider: Optional[LLMProvider] = None, bus: Optional[EventBus] = None,
                 validators: list = None, post_commit_hooks: list = None,
                 database_id: str | None = None, book_id: str | None = None,
                 analysis_mode: str = "cloud_model"):
        self._validators = validators  # lazy load if None
        self._post_commit_hooks = post_commit_hooks
        self.provider = provider or get_provider()
        self.bus = bus or EventBus.get()
        self.database_id = database_id
        self.book_id = book_id
        self.analysis_mode = analysis_mode
        self._splitter = None  # lazy import ChapterSplitter
        self._analyzer = None
        self._resolver = None

    @property
    def splitter(self):
        if self._splitter is None:
            from services.world_import.interfaces import RegexChapterSplitter
            self._splitter = RegexChapterSplitter()
        return self._splitter

    @property
    def analyzer(self):
        if self._analyzer is None:
            if self.analysis_mode == "local_rules":
                from services.world_import.rule_analyzer import RuleBasedChapterAnalyzer

                self._analyzer = RuleBasedChapterAnalyzer()
            elif self.analysis_mode == "cloud_model":
                from services.world_import.interfaces import LLMChapterAnalyzer

                self._analyzer = LLMChapterAnalyzer(
                    self.provider,
                    database_id=self.database_id,
                    book_id=self.book_id,
                )
            else:
                raise ValueError("Unsupported import analysis mode")
        return self._analyzer

    @property
    def resolver(self):
        if self._resolver is None:
            from services.world_import.interfaces import NameBasedEntityResolver
            self._resolver = NameBasedEntityResolver()
        return self._resolver

    # ── Preview (no DB writes) ─────────────────────────────────────────────

    @property
    def validators(self):
        if self._validators is None:
            from services.world_import.interfaces import DefaultChangeSetValidator
            self._validators = [DefaultChangeSetValidator()]
        return self._validators

    @property
    def post_commit_hooks(self):
        if self._post_commit_hooks is None:
            self._post_commit_hooks = []
        return self._post_commit_hooks

    # ── Preview (no DB writes) ─────────────────────────────────────────────

    MAX_INPUT_LENGTH = 50000

    def preview(self, text: str, book_id: str = "default") -> ImportChangeSet:
        self.book_id = book_id
        # V-015: cap input length
        if len(text) > self.MAX_INPUT_LENGTH:
            text = text[:self.MAX_INPUT_LENGTH] + f"\n[TRUNCATED at {self.MAX_INPUT_LENGTH} chars]"

        """Run the pipeline up to the build stage. Returns a changeset for preview."""
        try:
            # Stage 1: Chapter split
            # [HOOK: before_chapter_split] reserved for PromptComposer
            self.bus.emit("before_chapter_split", text=text)
            chapters = self.splitter.split(text)
            # [HOOK: after_chapter_split] reserved for PromptComposer
            self.bus.emit("after_chapter_split", chapters=chapters)
            log.info("Pipeline: split %d chapters from text", len(chapters))

            # Stage 2: Chapter analysis (offline rules or configured model)
            # [HOOK: before_chapter_analysis] reserved for PromptComposer, LLMRouter
            self.bus.emit("before_chapter_analysis", chapters=chapters)
            analyses = [self.analyzer.analyze(ch, i) for i, ch in enumerate(chapters)]
            # [HOOK: after_chapter_analysis] reserved for EntityResolver
            self.bus.emit("after_chapter_analysis", analyses=analyses)
            log.info("Pipeline: analyzed %d chapters", len(analyses))

            # Stage 3: Cross-chapter merge
            # [HOOK: before_cross_chapter] reserved for EntityResolver, ConsistencyChecker
            self.bus.emit("before_cross_chapter", analyses=analyses)
            merged = self.resolver.merge(analyses)
            # [HOOK: after_cross_chapter] reserved for ConsistencyChecker
            self.bus.emit("after_cross_chapter", merged=merged)
            log.info("Pipeline: merged %d entities, %d relations",
                     len(merged.get("entities", [])),
                     len(merged.get("relations", [])))

            # Stage 4: Build changeset
            # [HOOK: before_changeset_build] reserved for ConsistencyChecker
            self.bus.emit("before_changeset_build", data=merged)
            changeset = ImportChangeSet(
                entities=merged.get("entities", []),
                relations=merged.get("relations", []),
                book_id=book_id,
                chapters=chapters,
                chapter_analyses=analyses,
                warnings=list(dict.fromkeys(
                    warning
                    for analysis in analyses
                    for warning in analysis.get("warnings", [])
                    if isinstance(warning, str) and warning
                )),
                unresolved_items=[
                    item
                    for analysis in analyses
                    for item in analysis.get("unresolved_items", [])
                    if isinstance(item, dict)
                ],
                model=self.analyzer.name,
            )
            # [HOOK: after_changeset_build] reserved for ConsistencyChecker
            self.bus.emit("after_changeset_build", changeset=changeset)

            return changeset

        except Exception as e:
            # [HOOK: on_import_failed] reserved for all modules
            self.bus.emit("on_import_failed", error=str(e))
            log.error("Pipeline preview failed: %s", e)
            raise

    # ── Commit (writes to DB) ──────────────────────────────────────────────

    def commit(
        self,
        changeset: ImportChangeSet,
        db=None,
        before_commit=None,
        database_id: str | None = None,
        idempotency_key: str | None = None,
    ) -> dict:
        """Commit a previewed changeset. Writes to DB, updates vector store + global index."""
        # [HOOK: before_commit] reserved for GlobalIndex, VectorStore
        self.bus.emit("before_commit", changeset=changeset)

        from services.db import get_db
        from app.config import ENTITY_PREFIXES
        import json

        owns_connection = db is None
        db = db or get_db()
        try:
            cursor = db.cursor()
            cursor.execute(
                "CREATE TABLE IF NOT EXISTS import_task_receipts ("
                "task_id TEXT PRIMARY KEY,mode TEXT NOT NULL,result_json TEXT NOT NULL,"
                "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)"
            )
            if idempotency_key:
                receipt = cursor.execute(
                    "SELECT result_json FROM import_task_receipts WHERE task_id=?",
                    (idempotency_key,),
                ).fetchone()
                if receipt:
                    result = json.loads(receipt[0])
                    result["idempotent_replay"] = True
                    try:
                        from services.vector_store import connection_db_path, embedding_runtime_summary
                        from services.embedding_tasks import enqueue_entity_sync_task_by_path
                        vector_task = enqueue_entity_sync_task_by_path(
                            connection_db_path(db), list(result.get("entity_id_map", {}).values())
                        )
                        result["vector_task_id"] = vector_task["id"]
                        result["vector_indexed"] = vector_task["status"] == "completed"
                        result["embedding_runtime"] = embedding_runtime_summary()
                    except Exception:
                        result["vector_indexed"] = False
                    return result

            changeset.cleanup()
            if changeset.is_empty():
                raise ValueError("Changeset contains no valid entities")
            validation_warnings = changeset.validate()
            for validator in self.validators:
                validation_warnings.extend(validator.validate(changeset))
            validation_warnings = list(dict.fromkeys(validation_warnings))
            if changeset.conflicts or changeset.unresolved_items:
                raise ValueError("Changeset contains unresolved items")

            entity_id_map = {}
            created_count = 0
            relation_count = 0
            book_id_val = changeset.book_id
            unresolved_relations = []

            for ent in changeset.entities:
                etype = ent.get("type", "concept")
                prefix = ENTITY_PREFIXES.get(etype, "GEN")
                title = ent.get("title", "")
                existing = cursor.execute(
                    "SELECT entity_id FROM entities "
                    "WHERE title=? AND book_id=? AND is_active=1 "
                    "ORDER BY updated_at DESC, created_at DESC LIMIT 1",
                    (title, book_id_val),
                ).fetchone()
                if existing:
                    entity_id_map[title] = existing[0]
                    continue
                cursor.execute(
                    "INSERT INTO id_sequence (prefix, next_id) VALUES (?, 1) ON CONFLICT(prefix) DO UPDATE SET next_id = next_id + 1",
                    (prefix,))
                nid = cursor.execute("SELECT next_id FROM id_sequence WHERE prefix = ?", (prefix,)).fetchone()[0]
                entity_id = f"{prefix}_{nid:04d}"

                content = ent.get("content", "") or ""
                tags = ent.get("tags", [])
                importance = ent.get("importance", 3)
                tags_json = json.dumps(tags, ensure_ascii=False)
                cursor.execute(
                    "INSERT INTO entities (entity_id, entity_type, title, content, tags, importance, ai_summary, book_id) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                    (entity_id, etype, title, content, tags_json, importance, content[:500], book_id_val),
                )
                for tag in tags:
                    cursor.execute("INSERT INTO tag_index (entity_id, tag, book_id) VALUES (?, ?, ?)", (entity_id, tag.strip(), book_id_val))
                entity_id_map[title] = entity_id
                created_count += 1

            def resolve_relation_endpoint(title: str) -> str | None:
                title = (title or "").strip()
                if not title:
                    return None
                if title in entity_id_map:
                    return entity_id_map[title]
                row = cursor.execute(
                    "SELECT entity_id FROM entities "
                    "WHERE title=? AND book_id=? AND is_active=1 "
                    "ORDER BY updated_at DESC, created_at DESC LIMIT 1",
                    (title, book_id_val),
                ).fetchone()
                if row:
                    return row[0]
                return None

            for rel in changeset.relations:
                source_title = rel.get("source", "")
                target_title = rel.get("target", "")
                source_id = resolve_relation_endpoint(source_title)
                target_id = resolve_relation_endpoint(target_title)
                if not source_id or not target_id:
                    unresolved_relations.append(
                        f"{source_title or '?'} -> {target_title or '?'}"
                    )
                    continue
                existing = cursor.execute(
                    "SELECT id FROM relations "
                    "WHERE source_id=? AND target_id=? AND relation_type=? AND book_id=? "
                    "LIMIT 1",
                    (
                        source_id,
                        target_id,
                        rel.get("relation_type", "related_to"),
                        book_id_val,
                    ),
                ).fetchone()
                if existing:
                    continue
                cursor.execute(
                    "INSERT INTO relations (source_id, target_id, relation_type, description, book_id) VALUES (?, ?, ?, ?, ?)",
                    (source_id, target_id, rel.get("relation_type", "related_to"),
                     rel.get("description", ""), book_id_val),
                )
                relation_count += 1

            if unresolved_relations:
                validation_warnings.append(
                    "Skipped unresolved relations: " + ", ".join(unresolved_relations[:20])
                )

            if validation_warnings:
                log.warning("Changeset validation warnings: %s", validation_warnings)

            result = {
                "created_entities": created_count,
                "created_relations": relation_count,
                "entity_id_map": entity_id_map,
                "warnings": validation_warnings,
                "database_id": database_id,
            }
            if before_commit is not None:
                before_commit(db)
            if idempotency_key:
                cursor.execute(
                    "INSERT INTO import_task_receipts(task_id,mode,result_json) VALUES(?,?,?)",
                    (idempotency_key, "entities", json.dumps(result, ensure_ascii=False)),
                )
            from services.db import sync_entity_fts
            for entity_id in entity_id_map.values():
                sync_entity_fts(db, entity_id)
            db.commit()

            # Update vector store
            try:
                from services.vector_store import connection_db_path, embedding_runtime_summary
                from services.embedding_tasks import enqueue_entity_sync_task_by_path
                vector_task = enqueue_entity_sync_task_by_path(
                    connection_db_path(db), list(entity_id_map.values())
                )
                result["vector_task_id"] = vector_task["id"]
                result["vector_indexed"] = vector_task["status"] == "completed"
                result["embedding_runtime"] = embedding_runtime_summary()
            except Exception as ve:
                log.warning("Vector store sync failed: %s", ve)
                result["vector_indexed"] = False
                result["embedding_runtime"] = {
                    "available": False,
                    "model_id": None,
                    "execution_provider": None,
                }

            # Sync global index
            try:
                from services.global_index import mark_database_dirty
                from services.database_registry import get_active_database_id
                mark_database_dirty(database_id or get_active_database_id(), "import commit")
            except Exception as ge:
                log.warning("Global index mark failed: %s", ge)

            # [HOOK: after_commit] reserved for GlobalIndex, VectorStore
            self.bus.emit("after_commit", result=result)

            # Run post-commit hooks
            for hook in self.post_commit_hooks:
                try:
                    hook.after_commit(changeset, result)
                except Exception as he:
                    log.warning("Post-commit hook '%s' failed: %s", hook.name, he)

            return result

        except Exception as e:
            db.rollback()
            log.error("Pipeline commit failed: %s", e)
            raise
        finally:
            if owns_connection:
                db.close()

    @staticmethod
    def get_hook_points() -> list:
        """Return list of all hook points for documentation."""
        return [
            "before_chapter_split",
            "after_chapter_split",
            "before_chapter_analysis",
            "after_chapter_analysis",
            "before_cross_chapter",
            "after_cross_chapter",
            "before_changeset_build",
            "after_changeset_build",
            "before_commit",
            "after_commit",
            "on_import_failed",
        ]
