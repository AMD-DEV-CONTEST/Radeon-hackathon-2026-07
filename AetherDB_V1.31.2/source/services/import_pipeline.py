@dataclass
class ImportChangeSet:
    """Result of the pipeline preview, ready for user confirmation."""
    entities: list = field(default_factory=list)
    relations: list = field(default_factory=list)
    book_id: str = "default"
    chapters: list = field(default_factory=list)
    chapter_analyses: list = field(default_factory=list)
    warnings: list = field(default_factory=list)
    conflicts: list = field(default_factory=list)
    unresolved_items: list = field(default_factory=list)
    source_type: str = "text"
    source_chapter_id: str = ""
    prompt_profile_id: str = ""
    model: str = ""
    created_at: str = ""

    def to_dict(self) -> dict:
        return {
            "entities": self.entities,
            "relations": self.relations,
            "book_id": self.book_id,
            "chapter_count": len(self.chapters),
        }

    def is_empty(self) -> bool:
        return len(self.entities) == 0

    @property
    def entity_count(self) -> int:
        return len(self.entities)

    @property
    def relation_count(self) -> int:
        return len(self.relations)

    def validate(self) -> list[str]:
        warnings = []
        for i, ent in enumerate(self.entities):
            if not ent.get("type"):
                warnings.append(f"Entity {i}: missing type")
            if not ent.get("title"):
                warnings.append(f"Entity {i}: missing title")
        for i, rel in enumerate(self.relations):
            if not rel.get("source"):
                warnings.append(f"Relation {i}: missing source")
            if not rel.get("target"):
                warnings.append(f"Relation {i}: missing target")
        if self.conflicts:
            warnings.append(f"Changeset has {len(self.conflicts)} unresolved conflicts")
        if self.unresolved_items:
            warnings.append(f"Changeset has {len(self.unresolved_items)} unresolved items")
        return warnings

    def cleanup(self) -> None:
        def clean_text(value):
            if not isinstance(value, str):
                return value
            return re.sub(r"<[^>]*>", "", value)

        def normalize_importance(value):
            if isinstance(value, bool):
                return 3
            if isinstance(value, (int, float)):
                return min(10, max(1, int(value)))
            if isinstance(value, str):
                normalized = value.strip().lower()
                named_values = {
                    "low": 2,
                    "medium": 5,
                    "high": 8,
                    "minor": 2,
                    "major": 8,
                    "低": 2,
                    "中": 5,
                    "中等": 5,
                    "高": 8,
                    "重要": 8,
                }
                if normalized in named_values:
                    return named_values[normalized]
                try:
                    return min(10, max(1, int(float(normalized))))
                except ValueError:
                    return 3
            return 3

        self.entities = [e for e in self.entities if e.get("title") and e.get("type")]
        self.relations = [r for r in self.relations if r.get("source") and r.get("target")]
        for ent in self.entities:
            for field_name in ("title", "content", "summary", "description"):
                if field_name in ent:
                    ent[field_name] = clean_text(ent[field_name])
            ent["importance"] = normalize_importance(ent.get("importance", 3))
        for rel in self.relations:
            for field_name in ("source", "target", "relation_type", "description"):
                if field_name in rel:
                    rel[field_name] = clean_text(rel[field_name])
        seen = set()
        deduped = []
        for e in self.entities:
            key = f"{e.get('type','')}:{e.get('title','')}"
            if key not in seen:
                seen.add(key)
                deduped.append(e)
        self.entities = deduped


