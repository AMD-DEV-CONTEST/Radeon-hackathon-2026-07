export type I18nKey = MessageKey

export const supportedLocales: Locale[] = ['zh-CN', 'en-US']

export const localeOptions: Array<{ label: string; value: Locale }> = [
  { label: '中文', value: 'zh-CN' },
  { label: 'English', value: 'en-US' },
]

const messages: Record<Locale, Record<MessageKey, string>> = {
  'zh-CN': zhCN,
  'en-US': enUS,
}

export function normalizeLocale(value: string | null | undefined): Locale {
  if (!value) return defaultLocale
  const normalized = value.toLowerCase()
  if (normalized.startsWith('en')) return 'en-US'
  if (normalized.startsWith('zh')) return 'zh-CN'
  return defaultLocale
}

export function translate(
  locale: Locale,
  key: I18nKey,
  params?: Record<string, string | number>
): string {
  const template = messages[locale][key] || messages[defaultLocale][key] || key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name) => {
    const value = params[name]
    return value === undefined ? match : String(value)
  })
}

export function routeTitleKey(routeName: unknown): I18nKey {
  const routeKeys: Record<string, I18nKey> = {
    Factory: 'route.chat',
    Agents: 'route.agents',
    AgentDetail: 'route.agents',
    AgentGroup: 'route.agentGroup',
    Knowledge: 'route.knowledge',
    Scheduler: 'route.scheduler',
    Extensions: 'route.extensions',
    ModelPool: 'route.modelPool',
    Benchmarks: 'route.benchmarks',
  }
  return typeof routeName === 'string' ? routeKeys[routeName] || 'common.unknownPage' : 'common.unknownPage'
}
