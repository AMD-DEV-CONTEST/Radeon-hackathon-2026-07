def main():
    builder = StoryGraphBuilder("World Facts 1924-2024")

    # Ensure decades exist
    for y in range(1920, 2030, 10):
        builder.add_phase(f"{y}s", f"{y}s")

    for label, year, decade in FACTS:
        builder.add_event(label, "", year, str(year))
        builder.in_phase(label, decade)

    builder.build()

    total = len(FACTS)
    cn = sum(1 for l, _, _ in FACTS if "[CN]" in l)
    gl = sum(1 for l, _, _ in FACTS if "[GL]" in l)
    print(f"Total facts: {total}")
    print(f"  China: {cn}")
    print(f"  Global: {gl}")
    per_yr = total / 100
    print(f"  Avg: {per_yr:.0f}/year")


if __name__ == "__main__":
    main()
