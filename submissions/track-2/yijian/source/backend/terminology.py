def select_terms(density: str, keywords: list[str] | None = None) -> list[dict]:
    limit = {"low": 2, "medium": 4, "high": 7}.get(density, 4)
    keywords = keywords or []
    scored = sorted(
        TERMS,
        key=lambda entry: (
            -sum(word in entry["term"] or word in entry["category"] for word in keywords),
            entry["id"],
        ),
    )
    return scored[:limit]
