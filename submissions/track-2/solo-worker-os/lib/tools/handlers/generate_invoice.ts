import { z } from 'zod';
import type { SupabaseClient } from '@supabase/supabase-js';
import type { ToolConfig } from '../types';
import type { Project } from '@/lib/types';
import { resolveProject } from '@/lib/tools/resolve-project';
import { syncWorkflowForProject } from '@/lib/workflow-sync';

// ─── Zod schema ────────────────────────────────────────────────────────────────
const InvoiceSchema = z.object({
  project_id: z.string().uuid().optional(),
  client_name: z.string().optional(),
  project_type: z.string().optional(),
  due_date: z.string().regex(/^\d{4}-\d{2}-\d{2}$/).optional(),
  notes: z.string().max(500).optional(),
}).refine(
  (data) => data.project_id || data.client_name,
  { message: 'Either project_id or client_name must be provided' }
);

// ─── Helper: generate invoice number ───────────────────────────────────────────
function generateInvoiceNumber(): string {
  const now = new Date();
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, '0');
  const rand = Math.random().toString(36).slice(2, 6).toUpperCase();
  return `INV-${y}${m}-${rand}`;
}

// ─── Helper: build invoice display text ────────────────────────────────────────
function buildInvoiceText(p: Project, invoiceNumber: string, dueDate?: string, notes?: string): string {
  const today = new Date().toISOString().slice(0, 10);
  const due = dueDate ?? p.deadline;
  return `# Invoice ${invoiceNumber}

**Bill To:** ${p.client_name}

## Project
${p.project_type}

## Amount Due
**${p.currency} ${Number(p.budget).toFixed(2)}**

## Dates
- Issued: ${today}
- Due: ${due}

${notes ? `## Notes\n${notes}\n` : ''}
## Payment Instructions
Please remit payment via bank transfer, WeChat Pay, or Alipay.
Contact the service provider for account details.

---
*Generated by Solo Worker OS on ${today}*
`;
}

// ─── Tool configuration ───────────────────────────────────────────────────────
export const generateInvoiceTool: ToolConfig = {
  name: 'generate_invoice',
  description: 'Generate an invoice for a project. Pass project_id (UUID) OR client_name to look up the project. The invoice amount defaults to the project budget. Optionally set a due_date and notes. When the user says "给张明开一张发票" or "为刘洋的项目生成账单", pass client_name.',
  input_schema: {
    type: 'object',
    properties: {
      project_id: { type: 'string', description: 'UUID of the project. Optional if client_name is given.' },
      client_name: { type: 'string', description: 'Client name to look up the project.' },
      project_type: { type: 'string', description: 'Optional: project type to disambiguate when a client has multiple projects.' },
      due_date: { type: 'string', description: 'Invoice due date in YYYY-MM-DD format. Defaults to project deadline.' },
      notes: { type: 'string', description: 'Optional notes to include on the invoice.' },
    },
    required: [],
  },
  subagent: 'general',
  tags: ['invoice', 'finance', 'generate'],
  modes: ['default', 'qwen', 'casper'],
  async handler(input, ctx) {
    const supabase = ctx.supabase as SupabaseClient;
    const { data: authData } = await supabase.auth.getUser().catch(() => ({ data: { user: null } }));
    const userId = authData?.user?.id;

    const parsed = InvoiceSchema.safeParse(input);
    if (!parsed.success) throw new Error(`Invalid input: ${parsed.error.message}`);
    const p = await resolveProject(supabase, parsed.data);
    const invoiceNumber = generateInvoiceNumber();
    const invoiceText = buildInvoiceText(p, invoiceNumber, parsed.data.due_date, parsed.data.notes);

    // Prevent status rollback: refuse to generate invoice if project is already paid or cancelled
    if (['paid', 'cancelled'].includes(p.status)) {
      throw new Error(`Cannot generate invoice: project "${p.project_type}" for ${p.client_name} is already ${p.status}.`);
    }

    const { data, error } = await supabase.from('invoices').insert({
      project_id: p.id,
      invoice_number: invoiceNumber,
      amount: Number(p.budget),
      currency: p.currency,
      status: 'sent' as const,
      issued_date: new Date().toISOString().slice(0, 10),
      due_date: parsed.data.due_date ?? p.deadline,
      notes: parsed.data.notes ?? null,
      ...(userId && { user_id: userId }),
    }).select().single();
    if (error) throw new Error(error.message);

    // Update project status to invoiced
    await supabase.from('projects').update({ status: 'invoiced' }).eq('id', p.id);

    // Sync workflow: advance to 'invoiced' stage
    await syncWorkflowForProject(supabase, p.id, 'invoiced');

    await supabase.from('agent_actions').insert({
      project_id: p.id,
      action_type: 'invoice_generated',
      payload: { invoice_id: data.id, invoice_number: invoiceNumber, amount: p.budget, currency: p.currency },
      ...(userId && { user_id: userId }),
    });

    return {
      toolResult: `Invoice ${invoiceNumber} generated for ${p.client_name} (${p.currency} ${Number(p.budget).toFixed(2)}). Invoice is already displayed to the user verbatim. Do NOT repeat the invoice; just confirm in one short sentence.`,
      clientSummary: `Generated invoice ${invoiceNumber} for "${p.project_type}" (${p.currency} ${Number(p.budget).toFixed(2)}).`,
      displayText: invoiceText,
    };
  },
};

export default generateInvoiceTool;
