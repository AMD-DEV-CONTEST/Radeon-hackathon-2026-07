"""Deterministic canonical role-graph projection and lexical normalization.

The projection reads only accepted canonical records.  It does not extract new
facts from raw text: roots are canonical critical moments, decisions and
insights, while edges only state that a canonical record has a member in a
declared role.
"""

from __future__ import annotations

import hashlib
import re
import unicodedata
from datetime import datetime
from uuid import NAMESPACE_URL, UUID, uuid5

from app.experience_asset.domain.enums import (
    Milestone,
    MilestoneState,
    ProjectionEdgeType,
    ProjectionLifecycle,
    ProjectionRootKind,
    ReadinessLifecycle,
    StatementStatus,
)
from app.experience_asset.domain.m4 import InsightBoundaryMapV1
from app.experience_asset.domain.models import ExperienceAssetV1, Statement
from app.experience_asset.domain.relation import (
    PROJECTION_SCHEMA_VERSION,
    KnowledgeCardReadinessRecordV1,
    NodeProvenanceV1,
    RoleGraphEdgeV1,
    RoleGraphNodeV1,
    RoleGraphProjectionV1,
    compute_projection_hash,
    role_graph_edge_id,
    role_graph_member_node_id,
    role_graph_root_node_id,
)

LEXICAL_NORMALIZATION_VERSION = "e5-lexical-normalization/v1"
UNICODE_NORMALIZATION_FORM = "NFKC"
UNICODE_DATA_VERSION = unicodedata.unidata_version
CJK_NGRAM_SIZE = 2
LATIN_CASEFOLD = True

_CJK_RE = re.compile(
    r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\u3040-\u30ff\uac00-\ud7af]+"
)
_TOKEN_RE = re.compile(
    r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\u3040-\u30ff\uac00-\ud7af]+"
    r"|[^\W\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\u3040-\u30ff\uac00-\ud7af]+",
    re.UNICODE,
)

_CRITICAL_ROLES = (
    (ProjectionEdgeType.HAS_CUE, "cue_statement_ids"),
    (ProjectionEdgeType.HAS_CHANGE, "change_statement_ids"),
    (ProjectionEdgeType.HAS_SURPRISE, "surprise_statement_ids"),
    (ProjectionEdgeType.HAS_CONFLICT, "conflict_statement_ids"),
)
_DECISION_ROLES = (
    (ProjectionEdgeType.HAS_ALTERNATIVE, "alternative_statement_ids"),
    (ProjectionEdgeType.HAS_REASON, "reason_statement_ids"),
    (ProjectionEdgeType.HAS_ACTION, "action_statement_ids"),
    (ProjectionEdgeType.HAS_RESULT, "result_statement_ids"),
    (ProjectionEdgeType.HAS_EVIDENCE, "evidence_statement_ids"),
)
_INSIGHT_ROLES = (
    (ProjectionEdgeType.HAS_SUPPORT, "support_statement_ids"),
    (ProjectionEdgeType.HAS_COUNTERFACTUAL, "counterfactual_statement_ids"),
    (ProjectionEdgeType.HAS_LIMITATION, "limitation_statement_ids"),
    (ProjectionEdgeType.HAS_COUNTEREXAMPLE, "counterexample_statement_ids"),
    (ProjectionEdgeType.HAS_APPLICABILITY, "applicability_statement_ids"),
)


def normalize_lexical_text(text: str) -> tuple[str, ...]:
    """Return reproducible word and CJK-bigram tokens for FTS5.

    NFKC is applied before case-folding so full-width Latin text and ordinary
    Latin text share one representation.  CJK n-grams are generated by the
    application rather than an optional SQLite tokenizer.
    """

    normalized = unicodedata.normalize(UNICODE_NORMALIZATION_FORM, text)
    if LATIN_CASEFOLD:
        normalized = normalized.casefold()

    tokens: list[str] = []
    for match in _TOKEN_RE.finditer(normalized):
        value = match.group(0)
        if _CJK_RE.fullmatch(value):
            if len(value) < CJK_NGRAM_SIZE:
                tokens.append(value)
            else:
                tokens.extend(
                    value[index : index + CJK_NGRAM_SIZE]
                    for index in range(len(value) - CJK_NGRAM_SIZE + 1)
                )
        else:
            tokens.append(value)
    return tuple(dict.fromkeys(tokens))


def summary_index_document(
    projection: RoleGraphProjectionV1, asset: ExperienceAssetV1
) -> tuple[str, str, str, str]:
    """Build the only text permitted in the cross-asset summary index."""

    ordered_nodes = sorted(projection.nodes, key=lambda item: item.display_order)
    summary_text = "\n".join(node.summary_text for node in ordered_nodes)
    role_signature = " ".join(
        sorted(
            {
                node.root_kind.value
                for node in ordered_nodes
            }
            | {node.role.value for node in ordered_nodes if node.role is not None}
        )
    )
    asset_title = ordered_nodes[0].summary_text if ordered_nodes else ""
    lexical_tokens = " ".join(
        normalize_lexical_text(f"{asset_title}\n{summary_text}\n{role_signature}")
    )
    return asset_title, summary_text, lexical_tokens, role_signature


def build_role_graph_projection(
    *,
    asset: ExperienceAssetV1,
    m4_artifact: InsightBoundaryMapV1,
    readiness: KnowledgeCardReadinessRecordV1,
    created_at: datetime,
) -> RoleGraphProjectionV1:
    """Project one exact ready canonical version into a deterministic graph."""

    accepted_states = {MilestoneState.CONFIRMED, MilestoneState.COMPLETE_WITH_GAPS}
    if readiness.lifecycle is not ReadinessLifecycle.ACTIVE:
        raise ValueError("role-graph projection requires ACTIVE readiness")
    if readiness.asset_id != asset.asset_id or readiness.version_id != asset.version_id:
        raise ValueError("readiness does not bind the supplied canonical asset version")
    if readiness.m4_artifact_id != m4_artifact.artifact_id:
        raise ValueError("readiness does not bind the supplied M4 artifact")
    if m4_artifact.asset_id != asset.asset_id or m4_artifact.state not in accepted_states:
        raise ValueError("projection requires an accepted M4 artifact for this asset")
    if asset.milestone_states[Milestone.M4] not in accepted_states:
        raise ValueError("the canonical M4 milestone is not accepted")
    m4_reference = next(
        (
            item
            for item in asset.milestone_artifacts
            if item.milestone is Milestone.M4
            and item.state in accepted_states
            and item.payload.get("m4_artifact_id") == str(m4_artifact.artifact_id)
        ),
        None,
    )
    if m4_reference is None:
        raise ValueError("canonical state does not carry the readiness-bound M4 reference")

    projection_id = uuid5(
        NAMESPACE_URL,
        ":".join(
            (
                PROJECTION_SCHEMA_VERSION,
                str(asset.asset_id),
                str(asset.version_id),
                readiness.knowledge_card_hash,
            )
        ),
    )
    statements = {statement.statement_id: statement for statement in asset.statements}
    excluded = set(readiness.accepted_gap_statement_ids)

    def accepted(statement_ids: list[UUID]) -> list[Statement]:
        return [
            statements[statement_id]
            for statement_id in statement_ids
            if statement_id in statements
            and statement_id not in excluded
            and statements[statement_id].status is not StatementStatus.UNRESOLVED
        ]

    nodes: list[RoleGraphNodeV1] = []
    edges: list[RoleGraphEdgeV1] = []
    provenance: list[NodeProvenanceV1] = []

    def append_record(
        *,
        root_kind: ProjectionRootKind,
        record_id: UUID,
        root_text: str,
        root_statements: list[Statement],
        members: list[tuple[ProjectionEdgeType, list[Statement]]],
    ) -> None:
        all_grounding = root_statements or [item for _, values in members for item in values]
        if not all_grounding:
            return
        root_id = role_graph_root_node_id(
            root_kind=root_kind, canonical_record_id=record_id
        )
        append_node(
            node_id=root_id,
            root_kind=root_kind,
            record_id=record_id,
            role=None,
            text=root_text,
            grounding=all_grounding,
        )
        for role, member_statements in members:
            for statement in member_statements:
                member_id = role_graph_member_node_id(
                    root_kind=root_kind,
                    canonical_record_id=record_id,
                    role=role,
                    display_order=len(nodes),
                )
                append_node(
                    node_id=member_id,
                    root_kind=root_kind,
                    record_id=record_id,
                    role=role,
                    text=statement.text,
                    grounding=[statement],
                )
                edges.append(
                    RoleGraphEdgeV1(
                        edge_id=role_graph_edge_id(
                            root_node_id=root_id,
                            member_node_id=member_id,
                            edge_type=role,
                        ),
                        projection_id=projection_id,
                        edge_type=role,
                        root_node_id=root_id,
                        member_node_id=member_id,
                        canonical_record_id=record_id,
                    )
                )

    def append_node(
        *,
        node_id: str,
        root_kind: ProjectionRootKind,
        record_id: UUID,
        role: ProjectionEdgeType | None,
        text: str,
        grounding: list[Statement],
    ) -> None:
        nodes.append(
            RoleGraphNodeV1(
                node_id=node_id,
                projection_id=projection_id,
                root_kind=root_kind,
                canonical_record_id=record_id,
                is_root=role is None,
                role=role,
                display_order=len(nodes),
                summary_text=text[:400],
                summary_text_hash=hashlib.sha256(text[:400].encode("utf-8")).hexdigest(),
            )
        )
        provenance.append(
            NodeProvenanceV1(
                node_id=node_id,
                projection_id=projection_id,
                statement_ids=sorted(
                    {statement.statement_id for statement in grounding}, key=str
                ),
                evidence_refs=sorted(
                    {
                        str(reference)
                        for statement in grounding
                        for reference in statement.derived_from
                    }
                ),
                source_refs=sorted(
                    {
                        str(reference)
                        for statement in grounding
                        for reference in statement.source_refs
                    }
                ),
            )
        )

    for moment in sorted(
        asset.critical_moments,
        key=lambda item: (item.order, str(item.moment_id)),
    ):
        members = [(role, accepted(getattr(moment, field))) for role, field in _CRITICAL_ROLES]
        append_record(
            root_kind=ProjectionRootKind.CRITICAL_MOMENT,
            record_id=moment.moment_id,
            root_text=moment.title,
            root_statements=[],
            members=members,
        )
    for decision in asset.decisions:
        members = [(role, accepted(getattr(decision, field))) for role, field in _DECISION_ROLES]
        append_record(
            root_kind=ProjectionRootKind.DECISION_RECORD,
            record_id=decision.decision_id,
            root_text=decision.summary,
            root_statements=accepted(decision.decision_statement_ids),
            members=members,
        )
    m4_entries = {entry.insight_id: entry for entry in m4_artifact.entries}
    for insight in asset.insights:
        entry = m4_entries.get(insight.insight_id)
        lesson_ids = (
            [
                statement.statement_id
                for statement in entry.statements
                if statement.role == "LESSON" and not statement.is_visible_gap
            ]
            if entry is not None
            else []
        )
        members = [(role, accepted(getattr(insight, field))) for role, field in _INSIGHT_ROLES]
        append_record(
            root_kind=ProjectionRootKind.INSIGHT_RECORD,
            record_id=insight.insight_id,
            root_text=insight.lesson,
            root_statements=accepted(lesson_ids),
            members=members,
        )

    projection_hash = compute_projection_hash(
        asset_id=asset.asset_id,
        version_id=asset.version_id,
        knowledge_card_hash=readiness.knowledge_card_hash,
        projection_schema_version=PROJECTION_SCHEMA_VERSION,
        nodes=nodes,
        edges=edges,
        provenance=provenance,
    )
    return RoleGraphProjectionV1(
        projection_id=projection_id,
        asset_id=asset.asset_id,
        version_id=asset.version_id,
        knowledge_card_hash=readiness.knowledge_card_hash,
        projection_hash=projection_hash,
        lifecycle=ProjectionLifecycle.ACTIVE,
        nodes=nodes,
        edges=edges,
        provenance=provenance,
        created_at=created_at,
    )
