  function normalizeLanguage(value) {
    return SUPPORTED_LANGUAGES.has(value) ? value : "en";
  }

  function readLanguage(storage) {
    try {
      return normalizeLanguage(storage?.getItem(STORAGE_KEY));
    } catch {
      return "en";
    }
  }

  function writeLanguage(storage, language) {
    const normalized = normalizeLanguage(language);
    try {
      storage?.setItem(STORAGE_KEY, normalized);
    } catch {
      // Storage can be unavailable in hardened browser contexts; the session still switches.
    }
    return normalized;
  }

  function translate(language, key, params = {}) {
    const normalized = normalizeLanguage(language);
    const template = catalogs[normalized]?.[key] ?? catalogs.en[key] ?? key;
    return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => (
      Object.hasOwn(params, name) ? String(params[name]) : match
    ));
  }

  function demoPrompt(language) {
    return translate(language, "workspace.promptPlaceholder");
  }

  function translateKnown(language, value) {
    const directKey = knownCopy[value];
    if (directKey) return translate(language, directKey);
    const retrieved = /^Retrieved (\d+) evidence items\.$/.exec(value);
    if (retrieved) {
      return normalizeLanguage(language) === "zh-CN"
        ? `已检索 ${retrieved[1]} 条证据。`
        : value;
    }
    const indexed = /^Indexed (\d+) workspace files\.$/.exec(value);
    if (indexed) {
      return normalizeLanguage(language) === "zh-CN"
        ? `已索引 ${indexed[1]} 个工作区文件。`
        : value;
    }
    if (value === "Submission structure is complete." && normalizeLanguage(language) === "zh-CN") {
      return "提交结构完整。";
    }
    if (normalizeLanguage(language) === "zh-CN") {
      if (value === "same-instance loopback") return "同实例回环";
      if (value === "AMD Cloud shared API") return "AMD 云共享 API";
      if (value === "workspace-confined; local state; audited tools") return "限定工作区；本地状态；工具可审计";
      if (value === "Radeon Cloud verified run") return "Radeon Cloud 已验证运行";
    }
    return value;
  }

