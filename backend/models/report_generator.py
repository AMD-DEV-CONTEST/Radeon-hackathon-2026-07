"""Report generation powered by the configured chat/llama backend.

This module no longer loads a local report model. Instead, it reuses the same
chat backend (OpenAI-compatible llama-server, GGUF, ternary Qwen, etc.) that
answers follow-up questions. A report is generated by sending the chest X-ray
image plus a radiology-specific system prompt to the server. When no server is
configured or available, a lightweight rule-based template fallback is used.
"""
import json
import os
import re
import time
from io import BytesIO
from typing import Any, Optional

from PIL import Image


def _encode_image(image: Optional[Image.Image]) -> Optional[str]:
    """Encode a PIL image as a base64 PNG string."""
    if image is None:
        return None
    buf = BytesIO()
    image.convert("RGB").save(buf, format="PNG")
    return _b64encode(buf.getvalue()).decode("utf-8")


def _b64encode(data: bytes) -> bytes:
    import base64
    return base64.b64encode(data)


REPORT_SYSTEM_PROMPT = (
    "You are an expert radiologist. Write only the FINDINGS section of a chest X-ray "
    "radiology report. Use the X-ray image and the supplied predicted findings as evidence, "
    "but do not blindly repeat predictions that are not supported by the image. Write one "
    "concise, fluent paragraph in standard radiologist style. Do not enumerate findings, "
    "provide explanations or reasoning, include recommendations, or add an IMPRESSION section."
)


class ReportResult:
    """Result returned by report generation."""

    def __init__(
        self,
        report: str,
        tokens_generated: int,
        latency_seconds: float,
        sections: dict[str, str],
        chat_seed: Optional[list[dict[str, Any]]] = None,  # NEW
        source: str = "template",
    ):
        self.report = report
        self.tokens_generated = tokens_generated
        self.latency_seconds = latency_seconds
        self.sections = sections
        self.chat_seed = chat_seed or []
        self.source = source


class ReportGenerator:
    """Generate a radiology report by sending the image + prompt to the chat server."""

    def __init__(self, chat_engine: Optional[Any] = None, device: str = "cpu"):
        self.device = device
        self.chat_engine = chat_engine
        self.model_name = os.environ.get("REPORT_MODEL") or os.environ.get("CHAT_MODEL", "llama-server")
        self.max_new_tokens = int(os.environ.get("REPORT_MAX_TOKENS", "512"))
        self.system_prompt = REPORT_SYSTEM_PROMPT

    def generate(
        self,
        image: Optional[Image.Image] = None,
        findings: Optional[list] = None,
        structured_findings: Optional[dict[str, Any]] = None,
        image_info: Optional[dict] = None,
        max_new_tokens: Optional[int] = None,
    ) -> ReportResult:
        if findings is None:
            findings = []
        max_new_tokens = max_new_tokens if max_new_tokens is not None else self.max_new_tokens

        start = time.time()
        report, tokens, chat_seed = self._try_server(image, findings, structured_findings, max_new_tokens)
        source = "llm" if report is not None else "template"
        if report is None:
            report, tokens = self._template_report(findings, structured_findings), 0
            chat_seed = []
        report = self._remove_no_finding(report)
        latency = time.time() - start
        sections = self._split_report_sections(report)
        return ReportResult(
            report=report,
            tokens_generated=tokens,
            latency_seconds=latency,
            sections=sections,
            chat_seed=chat_seed,
            source=source,
        )

    def stream(
        self,
        image: Optional[Image.Image] = None,
        findings: Optional[list] = None,
        structured_findings: Optional[dict[str, Any]] = None,
        max_new_tokens: Optional[int] = None,
    ):
        """Yield report text as it is generated by the shared chat backend."""
        findings = findings or []
        max_new_tokens = max_new_tokens if max_new_tokens is not None else self.max_new_tokens
        if self.chat_engine is None or not self.chat_engine.is_available():
            yield self._template_report(findings, structured_findings)
            return
        user_text = self._build_user_text(findings, structured_findings)
        try:
            yield from self.chat_engine.stream_answer(
                report="", findings=findings, question=user_text,
                max_new_tokens=max_new_tokens, temperature=0.7,
                image=image, system_prompt=self.system_prompt,
            )
        except Exception as exc:
            print(f"[report-generator] Streaming generation failed: {exc}")
            yield self._template_report(findings, structured_findings)

    def _try_server(
        self,
        image: Optional[Image.Image],
        findings: list,
        structured_findings: Optional[dict[str, Any]],
        max_new_tokens: int,
    ) -> tuple[Optional[str], int, list[dict[str, Any]]]:
        if self.chat_engine is None or not self.chat_engine.is_available():
            return None, 0, []

        try:
            from models.chat_llm import ChatLLM
            if not isinstance(self.chat_engine, ChatLLM):
                return None, 0, []
        except Exception:
            return None, 0, []

        user_text = self._build_user_text(findings, structured_findings)
        try:
            answer = self.chat_engine.answer(
                report="",
                findings=findings,
                question=user_text,
                max_new_tokens=max_new_tokens,
                temperature=0.7,
                image=image,
                system_prompt=self.system_prompt,
            )
            # Seed the follow-up chat session with exactly the exchange that
            # produced this report, including the image, so later questions
            # continue the same conversation instead of starting cold.
            chat_seed = [
                {"role": "system", "content": self.system_prompt},
                {
                    "role": "user",
                    "content": user_text,
                    "image_b64": _encode_image(image) if image is not None else None,
                },
                {"role": "assistant", "content": answer.text},
            ]
            return answer.text, answer.tokens_generated, chat_seed
        except Exception as exc:
            print(f"[report-generator] Server generation failed: {exc}")
            return None, 0, []

    def _build_user_text(
        self,
        findings: list,
        structured_findings: Optional[dict[str, Any]],
    ) -> str:
        if structured_findings is not None:
            data = structured_findings
        else:
            data = {
                "modality": "Chest X-ray",
                "findings": [
                    {"name": _normalize_name(f.label), "confidence": round(f.confidence, 4)}
                    for f in findings
                    if f.label.lower() != "no finding"
                ],
            }
        predicted_findings = data.get("findings", [])
        return (
            "Predicted Findings:\n"
            + json.dumps(predicted_findings, indent=2)
            + "\n\nWrite the FINDINGS section for this chest X-ray image and these predicted findings."
        )

    def chat(self, report: str, findings: list, question: str) -> str:
        """Rule-based fallback chat used when no dedicated chat backend is available."""
        if "simpler" in question.lower() or "plain" in question.lower():
            return self._simplify(report, findings)
        if "why" in question.lower() or "explain" in question.lower():
            return self._explain_finding(question, findings)
        if "important" in question.lower() or "most" in question.lower():
            return self._rank_findings(findings)
        return self._answer_general(report, findings, question)

    def _template_report(
        self,
        findings: list,
        structured_findings: Optional[dict[str, Any]] = None,
    ) -> str:
        """Fallback template report when the server is unavailable."""
        if structured_findings is not None:
            parsed = [
                (_title_name(f["name"]), float(f.get("confidence", 0.5)))
                for f in structured_findings.get("findings", [])
                if f.get("name", "").lower() != "no finding"
            ]
        else:
            parsed = [
                (f.label, f.confidence)
                for f in findings
                if f.label.lower() != "no finding"
            ]

        if not parsed:
            return (
                "FINDINGS:\n\n"
                "No acute cardiopulmonary abnormality is seen. The lungs are clear, "
                "the pleural spaces are unremarkable, and the cardiomediastinal silhouette is normal.\n\n"
                "IMPRESSION:\nNormal chest X-ray."
            )

        sentences = [_finding_sentence(label, conf) for label, conf in parsed]
        findings_text = " ".join(sentences)
        impression = ["IMPRESSION:"] + [f"{i}. {label}." for i, (label, _) in enumerate(parsed, 1)]
        return f"FINDINGS:\n\n{findings_text}\n\n" + "\n".join(impression)

    def _remove_no_finding(self, report: str) -> str:
        """Strip lines that mention the 'No finding' pseudo-finding."""
        cleaned_lines = []
        for line in report.splitlines():
            if "no finding" in line.lower():
                continue
            cleaned_lines.append(line)
        return "\n".join(cleaned_lines)

    def _split_report_sections(self, report: str) -> dict[str, str]:
        """Split a report into FINDINGS and IMPRESSION sections."""
        sections: dict[str, str] = {"findings": "", "impression": ""}
        current_key = None
        buffer = []
        for line in report.splitlines():
            upper = line.strip().upper()
            if upper.startswith("FINDINGS"):
                current_key = "findings"
                continue
            if upper.startswith("IMPRESSION"):
                if current_key:
                    sections[current_key] = "\n".join(buffer).strip()
                buffer = []
                current_key = "impression"
                continue
            if current_key:
                buffer.append(line)
        if current_key:
            sections[current_key] = "\n".join(buffer).strip()
        return sections

    def _simplify(self, report: str, findings: list) -> str:
        simple = []
        for f in findings:
            simple.append(
                f"- {f.label}: {f.confidence:.0%}. "
                f"This means the AI sees a pattern that looks like {f.label.lower()}."
            )
        return "Simpler explanation:\n" + "\n".join(simple)

    def _explain_finding(self, question: str, findings: list) -> str:
        for f in findings:
            if f.label.lower() in question.lower():
                return (
                    f"The model flagged {f.label} with {f.confidence:.0%} confidence because "
                    f"abnormalities were detected in the corresponding image region. "
                    f"Hover over '{f.label}' in the report to see the highlighted region."
                )
        return "The model based its report on the detected findings and their image regions. Hover over report terms to see visual evidence."

    def _rank_findings(self, findings: list) -> str:
        sorted_f = sorted(findings, key=lambda x: x.confidence, reverse=True)
        ranked = [
            f"{i+1}. {f.label} ({f.confidence:.0%})"
            for i, f in enumerate(sorted_f)
            if f.confidence > 0.15
        ]
        return "Findings ranked by confidence:\n" + "\n".join(ranked)

    def _answer_general(self, report: str, findings: list, question: str) -> str:
        return f"Based on the AI findings, here's the answer:\n{self._explain_finding(question, findings)}"


def _normalize_name(label: str) -> str:
    return label.lower().replace(" ", "_")


def _title_name(name: str) -> str:
    return name.replace("_", " ").title()


def _finding_sentence(label: str, confidence: float) -> str:
    """Return a prose sentence describing a single finding."""
    sentences = {
        "Cardiomegaly": "The cardiomediastinal silhouette is enlarged, consistent with cardiomegaly.",
        "Pleural effusion": "There is a pleural effusion, seen as dependent opacity blunting the costophrenic angle.",
        "Pneumonia": "There are patchy airspace opacities suggestive of pneumonia.",
        "Atelectasis": "There is linear atelectasis, with volume loss and crowded bronchovascular markings.",
        "Pneumothorax": "There is a possible pneumothorax, with a visible pleural line and absent lung markings peripheral to it.",
        "Consolidation": "There is focal consolidation, with airspace opacification and possible air bronchograms.",
        "Pulmonary edema": "There is pulmonary edema, with increased interstitial markings and possible alveolar opacities.",
        "No finding": "No acute cardiopulmonary abnormality is seen.",
    }
    return sentences.get(label, f"There is evidence of {label.lower()}.")
