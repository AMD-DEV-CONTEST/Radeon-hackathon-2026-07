def t(key: str, lang: str = "en") -> str:
    """Translate a key to the target language. Falls back to EN, then key itself."""
    entry = _I18N.get(key)
    if entry is None:
        return key
    return entry.get(lang, entry.get("en", key))


def get_lang_keywords(key: str, lang: str = "en") -> list[str]:
    """Return a list of bilingual keywords for ChatEngine matching."""
    raw = t(key, lang)
    # Always include both EN and ZH keywords for matching
    entry = _I18N.get(key, {})
    en_kw = entry.get("en", "").split()
    zh_kw = entry.get("zh", "")
    # For Chinese, split on common delimiters
    import re
    zh_parts = re.split(r'[\s,，、]+', zh_kw)
    return en_kw + zh_parts
