"""Pydantic request/response model definitions."""
from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field


class ChatRequest(BaseModel):
    """Chat request."""

    message: str = Field(..., description="natural language question from the user")
    session_id: str = Field(default="default", description="session identifier, used for context memory")


class ChatResponse(BaseModel):
    """Chat response."""

    answer: str = Field(default="", description="natural language answer generated by the agent")
    citations: list[dict[str, Any]] = Field(default_factory=list, description="citation list")
    sources: list[str] = Field(default_factory=list, description="source identifier list")
    source_details: list[dict[str, Any]] = Field(default_factory=list, description="source details (number, title, original excerpt)")
    status: str = Field(default="unknown", description="processing status: completed/partial/blocked/failed")
    trace_summary: dict[str, Any] | None = Field(default=None, description="trace summary information")


class HealthResponse(BaseModel):
    """Health check response."""

    status: str = Field(default="ok", description="service health status")
    rag_ready: bool = Field(default=False, description="whether the RAG retriever is ready")
    model_info: dict[str, Any] = Field(default_factory=dict, description="model configuration information")


class SessionHistoryResponse(BaseModel):
    """Session history response."""

    session_id: str = Field(..., description="session identifier")
    history: list[dict[str, Any]] = Field(default_factory=list, description="conversation history")
    session_ids: list[str] = Field(default_factory=list, description="all active session IDs")


class SessionSummary(BaseModel):
    """Session summary (for the history list)."""

    session_id: str = Field(..., description="session identifier")
    topic: str = Field(default="", description="topic distilled by the model (<= 15 tokens)")
    saved_at: float = Field(default=0, description="most recent save timestamp (seconds)")
    message_count: int = Field(default=0, description="message count")


class SessionListResponse(BaseModel):
    """Recent session list response."""

    sessions: list[SessionSummary] = Field(default_factory=list, description="recent sessions (up to 5)")


class IMWebhookResponse(BaseModel):
    """IM webhook callback response."""

    status: str = Field(default="ok", description="processing status")
    answer: str = Field(default="", description="reply content")
    platform: str = Field(default="unknown", description="IM platform identifier")
