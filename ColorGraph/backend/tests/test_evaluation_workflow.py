def test_subjective_review_is_blinded_randomized_and_aggregated_by_candidate() -> None:
    pairs = [
        ReviewPair(
            id="pair-1",
            source_id="shot-1",
            candidate_a_id="algorithm-alpha",
            candidate_b_id="algorithm-beta",
        ),
        ReviewPair(
            id="pair-2",
            source_id="shot-2",
            candidate_a_id="algorithm-alpha",
            candidate_b_id="algorithm-beta",
        ),
    ]
    session, key = build_blinded_review_session(
        "review-v1",
        pairs,
        _reviewers(),
        seed=20260728,
        viewing_environment=ViewingEnvironment(
            display_model="Reference Display",
            calibration_profile_sha256="0" * 64,
            white_point="D65",
            peak_luminance_nits=100,
            black_luminance_nits=0.01,
            color_space="Rec.709",
            eotf="BT.1886",
            ambient_lux=5,
            viewing_distance_meters=1.5,
            calibration_date=datetime.now(UTC),
        ),
    )
    public_payload = session.model_dump_json()
    assert "algorithm-alpha" not in public_payload
    assert "algorithm-beta" not in public_payload

    responses: list[ReviewResponse] = []
    for reviewer_session in session.sessions:
        for assignment in reviewer_session.assignments:
            mapping = key.mappings[
                f"{reviewer_session.reviewer_id}:{assignment.pair_id}"
            ]
            preference = (
                Preference.A
                if mapping[assignment.blind_a] == "algorithm-alpha"
                else Preference.B
            )
            responses.append(
                ReviewResponse(
                    session_id=session.session_id,
                    reviewer_id=reviewer_session.reviewer_id,
                    pair_id=assignment.pair_id,
                    preference=preference,
                    confidence=5,
                )
            )

    aggregate = aggregate_review_responses(session, key, responses)
    assert aggregate.minimum_three_experts_met
    assert all(summary.valid_ratings == 3 for summary in aggregate.pair_summaries)
    assert all(
        summary.candidate_a_preference == 1
        for summary in aggregate.pair_summaries
    )
    assert all(
        0 < summary.candidate_a_ci95_low < summary.candidate_a_ci95_high <= 1
        for summary in aggregate.pair_summaries
    )

    with pytest.raises(ValueError, match="at least three valid"):
        aggregate_review_responses(session, key, responses[:-1])
