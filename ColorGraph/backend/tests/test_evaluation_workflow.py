def _acceptance_gate_policy(
    root: Path,
    manifest_path: Path,
    gates: dict[str, dict[str, float]],
) -> Path:
    manifest = load_gold_set_manifest(manifest_path)
    gate_sections = {
        path.partition(".")[0]
        for path in gates
    }
    task_by_section = {
        "analysis": "analysis",
        "representative": "representative_frame",
        "scene": "scene",
        "ranking": "ranking",
        "repair": "repair",
        "mask": "semantic_mask",
    }
    calibration_material_ids = {
        section: [
            item.id
            for item in manifest.items
            if item.split.value == "calibration"
            and item.task.value == task_by_section[section]
        ]
        for section in sorted(gate_sections)
    }
    calibration_path = root / "acceptance-calibration-observations.json"
    calibration_path.write_text(
        json.dumps(
            {
                "schema_version": (
                    "colorgraph.gold-calibration-observations/v1"
                ),
                "manifest_id": manifest.id,
                "manifest_version": manifest.version,
                "section_material_ids": calibration_material_ids,
                "gates": gates,
                "test_materials_accessed": False,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    path = root / "acceptance-gate-policy.json"
    path.write_text(
        json.dumps(
            {
                "schema_version": "colorgraph.gold-gate-policy/v1",
                "policy_id": "acceptance-unit-test-policy",
                "created_at": "2026-07-30T02:00:00Z",
                "manifest_id": manifest.id,
                "manifest_version": manifest.version,
                "manifest_sha256": _sha256(manifest_path),
                "annotation_guideline_version": (
                    manifest.annotation_guideline_version
                ),
                "calibration_observation_path": calibration_path.name,
                "calibration_observation_sha256": _sha256(
                    calibration_path
                ),
                "calibration_material_ids": calibration_material_ids,
                "gates": gates,
                "approved_by": ["independent-gate-reviewer"],
                "test_materials_accessed": False,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    return path


