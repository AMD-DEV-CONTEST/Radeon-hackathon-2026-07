# Shared settings for the setup scripts.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENVS="${V2M_VENVS:-$HOME/venvs}"
THIRD="${V2M_THIRD_PARTY:-$HOME/video2motion-deps}"
PY="${V2M_PYTHON:-python3.12}"
ROCM_INDEX="${V2M_ROCM_INDEX:-https://repo.radeon.com/rocm/manylinux/rocm-rel-7.2.1/}"
# Where the image's prebuilt ROCm torch wheels live. On the AMD cloud image they
# sit in /. No public index carries these exact builds, so the local files are
# preferred and the index is only a fallback.
# Trailing slash is stripped: with ROCM_WHEELS="/" the glob would produce
# "//torch-*.whl", and pip reads a leading "//" as a URL authority and rejects
# it with "non-local file URIs are not supported on this platform".
ROCM_WHEELS="${V2M_ROCM_WHEELS:-/}"
ROCM_WHEELS="${ROCM_WHEELS%/}"

# Optional PyPI mirror. The downloads dominate install time — measured 311 kB/s
# from pypi.org on our machine, which turns a 90 min install into 4 h. Set e.g.
#   export V2M_PIP_INDEX=https://pypi.tuna.tsinghua.edu.cn/simple
# The ROCm wheels always come from repo.radeon.com and are not affected.
PIP_INDEX="${V2M_PIP_INDEX:-}"
PIP_OPTS=""
if [ -n "$PIP_INDEX" ]; then
  PIP_HOST=$(printf '%s' "$PIP_INDEX" | sed -E 's#^[a-z]+://([^/]+).*#\1#')
  # PyPI stays as a fallback: mirrors lag, and some packages are missing from
  # them entirely (the Tsinghua mirror has no mujoco_playground, which aborts
  # the install if --index-url is used on its own).
  PIP_OPTS="--index-url $PIP_INDEX --extra-index-url https://pypi.org/simple --trusted-host $PIP_HOST"
fi

step() { printf '\n\033[1;31m▶ %s\033[0m\n' "$*"; }
info() { printf '  %s\n' "$*"; }
die()  { printf '\n\033[1;31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

need_cmd() { command -v "$1" >/dev/null 2>&1 || die "missing command: $1 (see scripts/setup_system.sh)"; }

write_env() {
  cat > "$REPO/env.sh" <<ENVEOF
# Generated by scripts/setup.sh — source this before running anything.
export V2M_WORKDIR=$REPO/workdir
export V2M_GVHMR=$THIRD/GVHMR
export V2M_GMR=$THIRD/GMR
export V2M_UNITREE_MUJOCO=$THIRD/unitree_mujoco
export V2M_PY_MJX=$VENVS/mjx/bin/python
export V2M_PY_GVHMR=$VENVS/gvhmr/bin/python
export V2M_PY_GMR=$VENVS/gmr/bin/python
export CYCLONEDDS_HOME=$THIRD/cyclonedds_install
export LD_LIBRARY_PATH=\$CYCLONEDDS_HOME/lib:\${LD_LIBRARY_PATH:-}
export CYCLONEDDS_URI=file://$THIRD/cyclonedds_lo.xml
export MUJOCO_GL=egl
export XLA_PYTHON_CLIENT_PREALLOCATE=false
export MPLBACKEND=Agg
ENVEOF
}
